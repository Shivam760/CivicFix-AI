"""File storage for evidence photos (architecture.md, "File Storage").

STORAGE_PROVIDER in backend/.env chooses where files go:
    local     a folder on this computer, backend/uploads (default; for development)
    supabase  a private Supabase Storage bucket, settings:
        SUPABASE_URL         https://<project>.supabase.co
        SUPABASE_SECRET_KEY  the project's secret (service role) key (never commit it)
        SUPABASE_BUCKET      bucket name, default "evidence"

Every storage has the same three methods, so the rest of the app never knows
which one it is using. Tests replace get_storage with an in-memory fake.
"""

import os
from functools import lru_cache
from pathlib import Path
from typing import Protocol

import httpx

from app.config import BACKEND_DIR
from app.errors import ApiError

LOCAL_UPLOAD_DIR = BACKEND_DIR / "uploads"


class StorageError(Exception):
    """A file could not be saved, read, or deleted."""


class Storage(Protocol):
    def save(self, key: str, data: bytes, content_type: str) -> None:
        """Store data under key. Fails if the key is already used."""

    def load(self, key: str) -> bytes:
        """Return the file stored under key."""

    def delete(self, key: str) -> None:
        """Remove the file stored under key, if it exists."""


class LocalStorage:
    """Files in a folder on this computer. Keys become paths inside root."""

    def __init__(self, root: Path):
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        # Keys are generated by the backend, but refuse anything like "../x"
        # that would point outside the upload folder anyway.
        if not path.is_relative_to(self.root) or path == self.root:
            raise StorageError("Invalid storage key.")
        return path

    def save(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            # "xb": create a new file for writing bytes; fail if it already exists.
            with path.open("xb") as file:
                file.write(data)
        except OSError as exc:
            raise StorageError("Could not save the file.") from exc

    def load(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except OSError as exc:
            raise StorageError("Could not read the file.") from exc

    def delete(self, key: str) -> None:
        try:
            self._path(key).unlink(missing_ok=True)
        except OSError as exc:
            raise StorageError("Could not delete the file.") from exc


class SupabaseStorage:
    """Files in a private Supabase Storage bucket, through its HTTP API.

    Pass a client only in tests, to fake Supabase's replies.
    """

    def __init__(self, url: str, secret_key: str, bucket: str, client: httpx.Client | None = None):
        self.bucket = bucket
        self.client = client or httpx.Client()
        self.base_url = f"{url.rstrip('/')}/storage/v1"
        # Supabase expects the key in both headers.
        self.headers = {"apikey": secret_key, "Authorization": f"Bearer {secret_key}"}

    def _request(
        self, method: str, path: str, failure: str, extra_headers: dict | None = None, **kwargs
    ) -> httpx.Response:
        headers = {**self.headers, **(extra_headers or {})}
        try:
            response = self.client.request(
                method, f"{self.base_url}/{path}", headers=headers, timeout=10, **kwargs
            )
        except httpx.HTTPError as exc:  # no connection, timeout, ...
            raise StorageError(failure) from exc
        if not response.is_success:
            # The status code only: the reply body could echo request details.
            raise StorageError(f"{failure} Supabase answered {response.status_code}.")
        return response

    def save(self, key: str, data: bytes, content_type: str) -> None:
        self._request(
            "POST",
            f"object/{self.bucket}/{key}",
            "Could not save the file.",
            content=data,
            # x-upsert false: fail instead of replacing an existing file.
            extra_headers={"Content-Type": content_type, "x-upsert": "false"},
        )

    def load(self, key: str) -> bytes:
        response = self._request(
            "GET", f"object/authenticated/{self.bucket}/{key}", "Could not read the file."
        )
        return response.content

    def delete(self, key: str) -> None:
        self._request(
            "DELETE",
            f"object/{self.bucket}",
            "Could not delete the file.",
            json={"prefixes": [key]},
        )


@lru_cache(maxsize=1)
def _supabase_storage(url: str, secret_key: str, bucket: str) -> SupabaseStorage:
    # Cached, so all requests share one HTTP connection pool.
    return SupabaseStorage(url, secret_key, bucket)


def get_storage() -> Storage:
    """FastAPI dependency. Tests override it with an in-memory fake."""
    provider = os.getenv("STORAGE_PROVIDER", "local")
    if provider == "local":
        return LocalStorage(LOCAL_UPLOAD_DIR)
    if provider == "supabase":
        url = os.getenv("SUPABASE_URL")
        secret_key = os.getenv("SUPABASE_SECRET_KEY")
        if url and secret_key:
            return _supabase_storage(url, secret_key, os.getenv("SUPABASE_BUCKET") or "evidence")
    raise ApiError(503, "STORAGE_UNAVAILABLE", "File storage is not configured.")
