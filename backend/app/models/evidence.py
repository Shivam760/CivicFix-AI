import uuid
from datetime import datetime

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    String,
    Text,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base
from app.models.choices import EVIDENCE_CONTENT_TYPES, EVIDENCE_KINDS, sql_list


class Evidence(Base):
    """Metadata about one photo attached to a report (database-schema.md section 11).

    The image itself lives in file storage under storage_key, not in PostgreSQL.
    Rows are never updated or deleted through the API.
    """

    __tablename__ = "evidence"
    __table_args__ = (
        CheckConstraint(f"kind IN ({sql_list(EVIDENCE_KINDS)})", name="kind_valid"),
        CheckConstraint(
            f"content_type IN ({sql_list(EVIDENCE_CONTENT_TYPES)})",
            name="content_type_valid",
        ),
        CheckConstraint("file_size_bytes > 0", name="file_size_positive"),
        CheckConstraint("btrim(file_name) <> ''", name="file_name_not_blank"),
        CheckConstraint("btrim(storage_key) <> ''", name="storage_key_not_blank"),
        # A blank description is stored as NULL, never as empty text.
        CheckConstraint(
            "description IS NULL OR btrim(description) <> ''",
            name="description_not_blank",
        ),
        # Supports "this report's photos, oldest first".
        Index("ix_evidence_report_id_uploaded_at", "report_id", "uploaded_at"),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    report_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("reports.id", ondelete="RESTRICT")
    )
    uploaded_by_user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="RESTRICT")
    )
    kind: Mapped[str] = mapped_column(String(30))
    # The uploaded file's name, for display only. Never used to build a path.
    file_name: Mapped[str] = mapped_column(String(255))
    # Where the file is in storage, generated by the backend. Unique, so two rows
    # can never point at the same file.
    storage_key: Mapped[str] = mapped_column(String(500), unique=True)
    content_type: Mapped[str] = mapped_column(String(100))
    file_size_bytes: Mapped[int] = mapped_column(BigInteger)
    description: Mapped[str | None] = mapped_column(Text)
    uploaded_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
